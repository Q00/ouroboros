_PYPROJECT = """\
[project]
name = "fixture-app"
version = "1.2.3"
requires-python = ">=3.12"
dependencies = ["pytest", "ruff"]
"""

# Top-level command keys, matching the detector's persisted format read by
# ``build_mechanical_config`` -> ``_apply_overrides``. Commands are declared by
# the fixture pyproject so the detector's entry-point validator accepts them.
_MECHANICAL_TOML = """\
# auto-generated by ouroboros evaluate detector
test = "uv run pytest"
lint = "ruff check ."
"""


def _write_fixture_repo(root: Path) -> None:
    (root / "pyproject.toml").write_text(_PYPROJECT, encoding="utf-8")
    ouroboros_dir = root / ".ouroboros"
    ouroboros_dir.mkdir(parents=True, exist_ok=True)
    (ouroboros_dir / "mechanical.toml").write_text(_MECHANICAL_TOML, encoding="utf-8")
    src = root / "src"
    src.mkdir()
    (src / "main.py").write_text("print('hi')\n", encoding="utf-8")
    (root / "tests").mkdir()


def _sample_seed(brownfield: BrownfieldContext | None = None) -> Seed:
    return Seed(
        goal="Build a task management CLI",
        brownfield_context=brownfield or BrownfieldContext(),
        constraints=("No external database",),
        acceptance_criteria=("Tasks can be created",),
        ontology_schema=OntologySchema(
            name="TaskManager",
            description="Task management ontology",
            fields=(OntologyField(name="tasks", field_type="array", description="Tasks"),),
        ),
        evaluation_principles=(
            EvaluationPrinciple(name="completeness", description="All requirements are met"),
        ),
        exit_conditions=(
            ExitCondition(
                name="done",
                description="All acceptance criteria satisfied",
                evaluation_criteria="pass",
            ),
        ),
        metadata=SeedMetadata(ambiguity_score=0.15),
    )


class TestScanner:
    def test_pack_from_fixture_repo(self, tmp_path: Path) -> None:
        _write_fixture_repo(tmp_path)
        pack = build_context_pack(tmp_path)
        assert pack is not None
        assert (
            "pyproject.toml: name fixture-app, version 1.2.3, requires-python >=3.12" in pack.stack
        )
        assert any(line.startswith("test:") and "pytest" in line for line in pack.verify_commands)
        rendered = render_context_pack(pack)
        assert "## Project Context (auto-detected facts)" in rendered
        assert "fixture-app" in rendered
        assert "uv run pytest" in rendered
        # Layout surfaces the top-level directories.
        assert "src/" in rendered

    def test_empty_dir_yields_no_pack(self, tmp_path: Path) -> None:
        assert build_context_pack(tmp_path) is None

    def test_nonexistent_path_yields_no_pack(self, tmp_path: Path) -> None:
        assert build_context_pack(tmp_path / "does-not-exist") is None

    def test_file_path_yields_no_pack(self, tmp_path: Path) -> None:
        f = tmp_path / "a.txt"
        f.write_text("x", encoding="utf-8")
        assert build_context_pack(f) is None

    def test_verify_commands_empty_without_toml(self, tmp_path: Path) -> None:
        (tmp_path / "pyproject.toml").write_text(_PYPROJECT, encoding="utf-8")
        assert detected_verify_commands(tmp_path) == ()

    def test_stack_only_still_produces_pack(self, tmp_path: Path) -> None:
        # A manifest with no mechanical.toml is enough (stack is a real fact).
        (tmp_path / "pyproject.toml").write_text(_PYPROJECT, encoding="utf-8")
        pack = build_context_pack(tmp_path)
        assert pack is not None
        assert pack.verify_commands == ()
        assert pack.stack


class TestBudget:
    def test_render_truncates_repo_map_first(self) -> None:
        huge_map = tuple(f"  dir_{i}_{'x' * 80}/" for i in range(500))
        pack = ContextPack(
            stack=("pyproject.toml: name fixture-app, version 1.2.3",),
            verify_commands=("test: uv run pytest",),
            repo_map=huge_map,
        )
        rendered = render_context_pack(pack)
        assert len(rendered) <= MAX_PACK_CHARS
        # Stack + verify facts survive truncation.
        assert "name fixture-app, version 1.2.3" in rendered
        assert "uv run pytest" in rendered


class TestCache:
    def _init_git(self, root: Path) -> None:
        subprocess.run(["git", "init", "-q"], cwd=root, check=True)
        subprocess.run(["git", "add", "-A"], cwd=root, check=True)
        subprocess.run(
            ["git", "-c", "user.email=t@t", "-c", "user.name=t", "commit", "-qm", "init"],
            cwd=root,
            check=True,
        )

    def test_cache_written_and_hit(self, tmp_path: Path) -> None:
        _write_fixture_repo(tmp_path)
        self._init_git(tmp_path)
        first = build_context_pack(tmp_path)
        assert first is not None
        cache_path = tmp_path / ".ouroboros" / "context_pack.json"
        assert cache_path.is_file()

        # Rewrite the cache with a sentinel stack but the same HEAD → a hit
        # must return the sentinel, proving the scan was skipped.
        import json

        data = json.loads(cache_path.read_text(encoding="utf-8"))
        data["stack"] = ["SENTINEL cached stack"]
        cache_path.write_text(json.dumps(data), encoding="utf-8")
        cached = build_context_pack(tmp_path)
        assert cached is not None
        assert cached.stack == ("SENTINEL cached stack",)

    def test_cache_miss_on_head_change(self, tmp_path: Path) -> None:
        _write_fixture_repo(tmp_path)
        self._init_git(tmp_path)
        build_context_pack(tmp_path)
        cache_path = tmp_path / ".ouroboros" / "context_pack.json"

        import json

        data = json.loads(cache_path.read_text(encoding="utf-8"))
        data["stack"] = ["SENTINEL cached stack"]
        cache_path.write_text(json.dumps(data), encoding="utf-8")

        # New commit → HEAD changes → the sentinel cache is stale and rescanned.
        (tmp_path / "extra.py").write_text("x = 1\n", encoding="utf-8")
        subprocess.run(["git", "add", "-A"], cwd=tmp_path, check=True)
        subprocess.run(
            ["git", "-c", "user.email=t@t", "-c", "user.name=t", "commit", "-qm", "second"],
            cwd=tmp_path,
            check=True,
        )
        fresh = build_context_pack(tmp_path)
        assert fresh is not None
        assert fresh.stack != ("SENTINEL cached stack",)
        assert any("fixture-app" in line for line in fresh.stack)

    def test_cache_miss_on_working_tree_source_change(self, tmp_path: Path) -> None:
        """Editing a parsed source with HEAD fixed must invalidate the cache.

        Regression for the HEAD-only cache key: the pack is built from mutable
        working-tree files, so a pyproject.toml edit without a commit used to
        keep serving the stale cached pack.
        """
        _write_fixture_repo(tmp_path)
        self._init_git(tmp_path)
        first = build_context_pack(tmp_path)
        assert first is not None
        assert any("name fixture-app, version 1.2.3" in line for line in first.stack)

        # Same HEAD, new working-tree manifest content → fresh pack, not cache.
        (tmp_path / "pyproject.toml").write_text(
            _PYPROJECT.replace('version = "1.2.3"', 'version = "9.9.9"'),
            encoding="utf-8",
        )
        fresh = build_context_pack(tmp_path)
        assert fresh is not None
        assert any("name fixture-app, version 9.9.9" in line for line in fresh.stack)
        assert not any("1.2.3" in line for line in fresh.stack)

    def test_non_git_dir_scans_without_cache(self, tmp_path: Path) -> None:
        _write_fixture_repo(tmp_path)
        pack = build_context_pack(tmp_path)
        assert pack is not None
        assert pack.head is None
        assert not (tmp_path / ".ouroboros" / "context_pack.json").is_file()

    def test_repo_map_is_fresh_after_uncommitted_toplevel_dir(self, tmp_path: Path) -> None:
        """A new uncommitted top-level dir must appear even on a cache hit.

        Regression for the layout-staleness gap: the cache fingerprint covers
        only manifests/HEAD, so adding a top-level directory without a commit
        left them unchanged. The repo map is now rebuilt fresh on every hit, so
        the cached layout can never go stale.
        """
        _write_fixture_repo(tmp_path)
        self._init_git(tmp_path)
        first = build_context_pack(tmp_path)
        assert first is not None
        assert not any("newpkg/" in line for line in first.repo_map)
        # The cache file exists, so the next build is a fingerprint/HEAD hit.
        assert (tmp_path / ".ouroboros" / "context_pack.json").is_file()

        # New uncommitted top-level dir: HEAD and the manifest fingerprint are
        # unchanged, yet the fresh repo map must surface it.
        (tmp_path / "newpkg").mkdir()
        (tmp_path / "newpkg" / "__init__.py").write_text("", encoding="utf-8")
        second = build_context_pack(tmp_path)
        assert second is not None
        assert any("newpkg/" in line for line in second.repo_map)
        # Stack/verify facts still come from the cache (proving it was a hit).
        assert second.stack == first.stack

    def test_repo_map_not_persisted_in_cache_artifact(self, tmp_path: Path) -> None:
        """The cached artifact must not carry repo map layout data."""
        import json

        _write_fixture_repo(tmp_path)
        self._init_git(tmp_path)
        build_context_pack(tmp_path)
        cache_path = tmp_path / ".ouroboros" / "context_pack.json"
        data = json.loads(cache_path.read_text(encoding="utf-8"))
        assert "repo_map" not in data

    def test_content_edit_invalidates_cache_when_mtime_and_size_are_preserved(
        self, tmp_path: Path
    ) -> None:
        import os

        _write_fixture_repo(tmp_path)
        self._init_git(tmp_path)
        before = build_context_pack(tmp_path)
        assert before is not None
        manifest = tmp_path / "pyproject.toml"
        original = manifest.stat()
        manifest.write_text(_PYPROJECT.replace("fixture-app", "changed-app"), encoding="utf-8")
        os.utime(manifest, ns=(original.st_atime_ns, original.st_mtime_ns))
        assert manifest.stat().st_size == original.st_size
        assert manifest.stat().st_mtime_ns == original.st_mtime_ns

        after = build_context_pack(tmp_path)

        assert after is not None
        assert any("changed-app" in line for line in after.stack)
        assert not any("fixture-app" in line for line in after.stack)


class TestSystemPromptInjection:
    def test_pack_present_when_flag_on(self, tmp_path: Path, monkeypatch) -> None:
        monkeypatch.setenv("OUROBOROS_CONTEXT_PACK", "1")
        _write_fixture_repo(tmp_path)
        prompt = build_system_prompt(_sample_seed(), repo_root=tmp_path)
        assert "## Project Context (auto-detected facts)" in prompt
        assert "fixture-app" in prompt

    def test_pack_absent_when_flag_off(self, tmp_path: Path, monkeypatch) -> None:
        monkeypatch.setenv("OUROBOROS_CONTEXT_PACK", "0")
        _write_fixture_repo(tmp_path)
        prompt = build_system_prompt(_sample_seed(), repo_root=tmp_path)
        assert "## Project Context (auto-detected facts)" not in prompt

    def test_explicit_contract_mode_outranks_later_environment_change(
        self,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        _write_fixture_repo(tmp_path)
        monkeypatch.setenv("OUROBOROS_CONTEXT_PACK", "0")
        enabled_prompt = build_system_prompt(
            _sample_seed(),
            repo_root=tmp_path,
            context_pack_enabled=True,
        )
        monkeypatch.setenv("OUROBOROS_CONTEXT_PACK", "1")
        disabled_prompt = build_system_prompt(
            _sample_seed(),
            repo_root=tmp_path,
            context_pack_enabled=False,
        )

        assert "## Project Context (auto-detected facts)" in enabled_prompt
        assert "## Project Context (auto-detected facts)" not in disabled_prompt

    def test_pack_absent_for_empty_dir(self, tmp_path: Path, monkeypatch) -> None:
        monkeypatch.setenv("OUROBOROS_CONTEXT_PACK", "1")
        prompt = build_system_prompt(_sample_seed(), repo_root=tmp_path)
        assert "## Project Context (auto-detected facts)" not in prompt

    def test_pack_absent_without_repo_root(self, monkeypatch) -> None:
        monkeypatch.setenv("OUROBOROS_CONTEXT_PACK", "1")
        prompt = build_system_prompt(_sample_seed())
        assert "## Project Context (auto-detected facts)" not in prompt

    def test_no_pack_without_trusted_repo_root_even_with_seed_reference(
        self, tmp_path: Path, monkeypatch
    ) -> None:
        """A raw seed reference must not drive a scan without a trusted repo_root.

        Regression for the containment gap: previously a seed's absolute
        ``context_references`` path was scanned with ``repo_root=None``. There
        is no stable base to contain seed paths against, so the pack must stay
        absent rather than reading from an arbitrary local repo.
        """
        monkeypatch.setenv("OUROBOROS_CONTEXT_PACK", "1")
        _write_fixture_repo(tmp_path)
        brownfield = BrownfieldContext(
            project_type="brownfield",
            context_references=(ContextReference(path=str(tmp_path), role="primary", summary=""),),
        )
        prompt = build_system_prompt(_sample_seed(brownfield), repo_root=None)
        assert "## Project Context (auto-detected facts)" not in prompt

    def test_out_of_tree_reference_is_rejected_and_never_scanned(
        self, tmp_path: Path, monkeypatch
    ) -> None:
        """An absolute seed reference outside repo_root cannot redirect the scan.

        Blocking regression: a hand-authored/imported seed pointing at an
        arbitrary local repo must not cause the pack to read from — or cache
        under — that repo. The pack must describe the contained ``repo_root``
        only, and no cache may be written beneath the outside directory.
        """
        monkeypatch.setenv("OUROBOROS_CONTEXT_PACK", "1")
        inside = tmp_path / "inside"
        inside.mkdir()
        _write_fixture_repo(inside)
        outside = tmp_path / "outside"
        outside.mkdir()
        (outside / "pyproject.toml").write_text(
            _PYPROJECT.replace('name = "fixture-app"', 'name = "SECRET-external-repo"'),
            encoding="utf-8",
        )

        brownfield = BrownfieldContext(
            project_type="brownfield",
            context_references=(ContextReference(path=str(outside), role="primary", summary=""),),
        )
        prompt = build_system_prompt(_sample_seed(brownfield), repo_root=inside)

        assert "## Project Context (auto-detected facts)" in prompt
        # Pack describes the contained repo, never the out-of-tree reference.
        assert "fixture-app" in prompt
        assert "SECRET-external-repo" not in prompt
        # No cache write leaked under the arbitrary outside repo.
        assert not (outside / ".ouroboros" / "context_pack.json").exists()


@pytest.mark.parametrize(
    "manifest,content,needle",
    [
        (
            "go.mod",
            "module example.com/app\n\ngo 1.22\n",
            "go.mod: module example.com/app, go 1.22",
        ),
        (
            "package.json",
            '{"name": "web", "version": "0.1.0"}',
            "package.json: name web, version 0.1.0",
        ),
        (
            "Cargo.toml",
            '[package]\nname = "tool"\nversion = "0.2.0"\nedition = "2021"\n',
            "Cargo.toml: name tool, version 0.2.0, edition 2021",
        ),
    ],
)
def test_other_language_stacks(tmp_path: Path, manifest: str, content: str, needle: str) -> None:
    (tmp_path / manifest).write_text(content, encoding="utf-8")
    pack = build_context_pack(tmp_path)
    assert pack is not None
    assert pack.stack == (needle,)


# A Python package whose root also carries an auxiliary ``package.json`` named
# like the project (Django's layout: setup.cfg metadata, a bare setup.py, and a
# package.json used only for JS linting and tests of the admin static files).
_DJANGO_LIKE_SETUP_CFG = """\
[metadata]
name = Django
version = attr: django.__version__

[options]
python_requires = >=3.6
"""

_DJANGO_LIKE_SETUP_PY = """\
from setuptools import setup

setup()
"""

_DJANGO_LIKE_PACKAGE_JSON = """\
{
  "name": "Django",
  "private": true,
  "scripts": {"test": "grunt test --verbose"},
  "devDependencies": {"eslint": "^6.8.0", "grunt": "^1.0.1"}
}
"""


class TestManifestFacts:
    def test_python_repo_with_auxiliary_package_json_lists_every_manifest(
        self, tmp_path: Path
    ) -> None:
        (tmp_path / "setup.cfg").write_text(_DJANGO_LIKE_SETUP_CFG, encoding="utf-8")
        (tmp_path / "setup.py").write_text(_DJANGO_LIKE_SETUP_PY, encoding="utf-8")
        (tmp_path / "package.json").write_text(_DJANGO_LIKE_PACKAGE_JSON, encoding="utf-8")

        pack = build_context_pack(tmp_path)

        assert pack is not None
        assert pack.stack == (
            "setup.cfg: name Django, python_requires >=3.6",
            "setup.py",
            "package.json: name Django",
        )
        rendered = render_context_pack(pack)
        assert "Manifests:\n- setup.cfg: name Django, python_requires >=3.6" in rendered
        # No line claims a language or framework for the repository.
        assert "Node" not in rendered
        assert "Stack:" not in rendered

    def test_pyproject_without_project_table_is_not_given_a_placeholder_name(
        self, tmp_path: Path
    ) -> None:
        (tmp_path / "pyproject.toml").write_text(
            "[build-system]\nrequires = ['setuptools>=40.8.0']\n", encoding="utf-8"
        )
        (tmp_path / "package.json").write_text(_DJANGO_LIKE_PACKAGE_JSON, encoding="utf-8")

        pack = build_context_pack(tmp_path)

        assert pack is not None
        assert pack.stack == ("pyproject.toml", "package.json: name Django")

    def test_pure_node_repo(self, tmp_path: Path) -> None:
        (tmp_path / "package.json").write_text(
            '{"name": "web", "version": "0.1.0", "engines": {"node": ">=18"}}',
            encoding="utf-8",
        )

        pack = build_context_pack(tmp_path)

        assert pack is not None
        assert pack.stack == ("package.json: name web, version 0.1.0, engines.node >=18",)

    def test_pure_python_setup_py_repo(self, tmp_path: Path) -> None:
        (tmp_path / "setup.py").write_text(
            "from setuptools import setup\n\nsetup(name='pkg', python_requires='>=3.8')\n",
            encoding="utf-8",
        )

        pack = build_context_pack(tmp_path)

        assert pack is not None
        # setup.py is code: its values are only known by running it, so only
        # the file's presence is reported, never a name read from the source.
        assert pack.stack == ("setup.py",)

    def test_setup_cfg_change_invalidates_cache(self, tmp_path: Path) -> None:
        subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)
        subprocess.run(
            [
                "git",
                "-c",
                "user.email=t@t",
                "-c",
                "user.name=t",
                "commit",
                "-q",
                "--allow-empty",
                "-m",
                "init",
            ],
            cwd=tmp_path,
            check=True,
        )
        (tmp_path / "setup.cfg").write_text(_DJANGO_LIKE_SETUP_CFG, encoding="utf-8")
        first = build_context_pack(tmp_path)
        assert first is not None

        (tmp_path / "setup.cfg").write_text(
            _DJANGO_LIKE_SETUP_CFG.replace("name = Django", "name = Renamed"), encoding="utf-8"
        )
        second = build_context_pack(tmp_path)

        assert second is not None
        assert second.stack == ("setup.cfg: name Renamed, python_requires >=3.6",)
